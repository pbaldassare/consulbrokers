-- Anagrafica controparti sinistri (lookup per apertura pratiche).

CREATE TABLE public.controparti_sinistri (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  codice integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  denominazione text NOT NULL,
  codice_fiscale text,
  partita_iva text,
  email text,
  telefono text,
  note text,
  attivo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  created_by uuid REFERENCES auth.users (id) ON DELETE SET NULL,
  CONSTRAINT controparti_sinistri_codice_key UNIQUE (codice),
  CONSTRAINT controparti_sinistri_denominazione_trim CHECK (char_length(trim(denominazione)) > 0)
);

CREATE UNIQUE INDEX controparti_sinistri_denominazione_norm_idx
  ON public.controparti_sinistri (lower(trim(denominazione)));

CREATE INDEX controparti_sinistri_attivo_idx ON public.controparti_sinistri (attivo);

COMMENT ON TABLE public.controparti_sinistri IS
  'Anagrafica controparti per sinistri (non clienti Consulnet).';

ALTER TABLE public.controparti_sinistri ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Staff full access controparti_sinistri"
  ON public.controparti_sinistri
  FOR ALL
  TO authenticated
  USING ((SELECT public.is_staff()))
  WITH CHECK ((SELECT public.is_staff()));

-- Seed da testo libero già usato su sinistri.controparte
INSERT INTO public.controparti_sinistri (denominazione)
SELECT DISTINCT trim(s.controparte)
FROM public.sinistri s
WHERE s.controparte IS NOT NULL
  AND trim(s.controparte) <> ''
  AND NOT EXISTS (
    SELECT 1
    FROM public.controparti_sinistri c
    WHERE lower(trim(c.denominazione)) = lower(trim(s.controparte))
  );

CREATE OR REPLACE FUNCTION public.search_controparti_sinistri_ranked(
  p_search text,
  p_limit integer DEFAULT 25,
  p_offset integer DEFAULT 0
)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO 'public'
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_limit integer := greatest(coalesce(p_limit, 25), 0);
  v_offset integer := greatest(coalesce(p_offset, 0), 0);
  v_term text;
  v_result jsonb;
BEGIN
  IF v_uid IS NULL OR NOT public.is_staff() THEN
    RETURN jsonb_build_object('total_count', 0, 'data', '[]'::jsonb);
  END IF;

  v_term := lower(trim(both FROM regexp_replace(coalesce(p_search, ''), '\s+', ' ', 'g')));

  IF v_term = '' THEN
    WITH scoped AS MATERIALIZED (
      SELECT c.*
      FROM public.controparti_sinistri c
      ORDER BY c.denominazione ASC
    )
    SELECT jsonb_build_object(
      'total_count', (SELECT count(*)::bigint FROM public.controparti_sinistri),
      'data', coalesce((
        SELECT jsonb_agg(to_jsonb(p) ORDER BY p.denominazione ASC)
        FROM (
          SELECT s.*
          FROM public.controparti_sinistri s
          ORDER BY s.denominazione ASC
          LIMIT v_limit OFFSET v_offset
        ) p
      ), '[]'::jsonb)
    ) INTO v_result;
  ELSE
    WITH scoped AS MATERIALIZED (
      SELECT c.*
      FROM public.controparti_sinistri c
      WHERE lower(c.denominazione) LIKE '%' || v_term || '%'
         OR lower(coalesce(c.codice_fiscale, '')) LIKE '%' || v_term || '%'
         OR lower(coalesce(c.partita_iva, '')) LIKE '%' || v_term || '%'
         OR lower(coalesce(c.email, '')) LIKE '%' || v_term || '%'
         OR lower(coalesce(c.telefono, '')) LIKE '%' || v_term || '%'
         OR c.codice::text LIKE '%' || v_term || '%'
    )
    SELECT jsonb_build_object(
      'total_count', (SELECT count(*)::bigint FROM scoped),
      'data', coalesce((
        SELECT jsonb_agg(to_jsonb(p) ORDER BY p.denominazione ASC)
        FROM (
          SELECT s.*
          FROM scoped s
          ORDER BY s.denominazione ASC
          LIMIT v_limit OFFSET v_offset
        ) p
      ), '[]'::jsonb)
    ) INTO v_result;
  END IF;

  RETURN coalesce(v_result, jsonb_build_object('total_count', 0, 'data', '[]'::jsonb));
END;
$$;

REVOKE ALL ON FUNCTION public.search_controparti_sinistri_ranked(text, integer, integer) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.search_controparti_sinistri_ranked(text, integer, integer) TO authenticated;

GRANT SELECT, INSERT, UPDATE, DELETE ON public.controparti_sinistri TO authenticated;
